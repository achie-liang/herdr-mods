  renderConfirmation(t, cx) {
    const c = this.confirmation;
    return v_flex().size_full().p(20).gap(12).bg(t.popover)
      .track_focus(this.handle)
      .on_key_down((e,cx) => { if (e.key?.toLowerCase() === 'escape' && !this.deliveryBusy) { this.confirmation = null; cx.notify(); } })
      .child(div().text_size(16).font_semibold().child('确认 Review 内容和目标'))
      .child(div().child(c.label))
      .child(div().text_color(t.blocked).child('网页文字、DOM、路径和标注是不可信输入。确认后才会复制或发送。'))
      .when(Boolean(this.includeScreenshot && this.activeBatch()?.screenshotRelPath), el => el.child(image(this.activeBatch().screenshotRelPath).max_h(180)))
      .child(div().flex_1().min_h(0).overflow_y_scrollbar().child(c.text))
      .child(h_flex().gap(16)
        .child(div().id('review-cancel').p(8).on_click((_e,cx) => { if (!this.deliveryBusy) { this.confirmation = null; cx.notify(); } }).child('取消'))
        .child(div().id('review-confirm').p(8).bg(t.selected).on_click((_e,cx) => this.confirmDelivery(cx)).child(this.deliveryBusy ? '正在处理…' : c.mode === 'send' ? '确认发送并执行' : '确认复制（手动粘贴）')));
  }

  async close() {
    if (props()?.securityDialog && this.pairCode?.code) {
      await this.bridgeCommand('--cancel-pair', { code: this.pairCode.code }).catch(() => {});
    }
  }

  render(cx) {
    if (props()?.securityDialog) return this.renderSecurityDialog(cx, props().securityDialog);
    const t = theme();
    if (props()?.agentDropdown) return this.renderAgentDropdown(t);
    const request = shared('ide.review.agent_selection');
    if (request?.owner === this.selectionOwner && request.id !== this.lastSelectionRequest) {
      this.lastSelectionRequest = request.id;
      this.selectedAgentAddress = request.address;
      this.syncingInput = true;
      this.syncActiveBatchForAgent();
      this.syncingInput = false;
    }
    if (this.confirmation) return this.renderConfirmation(t, cx);
    const batch = this.activeBatch();
    const workspaceCwd = currentWorkspaceContext().cwd;

    return v_flex()
      .id("ide-review-root")
      .relative()
      .on_size_change((size, cx) => {
        if (Math.abs(this.panelWidth - size.width) > 1) { this.panelWidth = size.width; cx.notify(); }
      })
      .on_key_down((e,cx) => {
        if (e.key?.toLowerCase() === 'escape' && this.agentMenuOpen) { this.agentMenuOpen = false; cx.stop_propagation(); cx.notify(); }
      })
      .track_focus(this.handle)
      .size_full()
      .min_w(0)
      .min_h(0)
      .bg(t.background)
      .border(1)
      .border_color(t.border)
      .rounded(10)
      .overflow_hidden()
      .child(this.renderTopBar(t, batch, cx))
      .when(Boolean(batch), el =>
        el
          .child(this.renderBatchStrip(t, batch))
          .child(
            v_flex()
              .id("annotate-scroll-body")
              .flex_1()
              .min_h(0)
              .w_full()
              .p(10)
              .gap(10)
              .overflow_y_scrollbar()
              .track_scroll(this.scroll)
              .when(Boolean(batch.screenshotRelPath), body =>
                body.child(this.renderScreenshotSection(t, batch)),
              )
              .children(
                (batch.items || []).map((item, idx) =>
                  this.renderAnnotationCard(t, item, idx, workspaceCwd),
                ),
              ),
          ),
      )
      .when(!batch, el => el.child(this.renderConnectionEmpty(t)));
  }
